// ---- Paleo-Hebrew (Old Hebrew) glyphs, 2026-08-16 ----
// Source: Noto Sans Phoenician 2.000 (Google, SIL OFL 1.1), rendered at 32px
// and cropped/centred into a common 32x26 cell.
//
// Why Phoenician codepoints for a Paleo-Hebrew feature: per Wikipedia's
// Paleo-Hebrew alphabet article, there is no difference between "Paleo-Hebrew"
// and "Phoenician" letter shapes -- the names are applied according to the
// language of the inscription, not the glyphs -- and the Unicode Phoenician
// block (U+10900-U+1091F) is explicitly intended to represent Palaeo-Hebrew,
// Siloam Hebrew and Hebrew seals alongside Phoenician. The block runs in
// alphabetical order, so alef..tav maps to U+10900..U+10915 with no judgement
// calls, and index i here is simply Hebrew letter i.
//
// CAVEAT: Noto's glyphs are a modern regularisation. Real Paleo-Hebrew was
// never standardised and appears in many variant shapes, growing more cursive
// between roughly 800 and 600 BCE. These forms are defensible and legible,
// but they are not any one inscription's hand.
//
// Format: XBM (LSB-first within each byte, rows padded to whole bytes), so
// these are drawn with Adafruit_GFX's drawXBitmap(), NOT drawBitmap().
// Total cost: 22 glyphs x 104 bytes = 2288 bytes of flash.

#define PALEO_W 32
#define PALEO_H 26
#define PALEO_BYTES_PER_GLYPH 104

